const fs = require('node:fs');
const path = require('node:path');

const { withDangerousMod } = require('expo/config-plugins');

/**
 * Shortens the push/pop animation, which is not reachable from JavaScript.
 *
 * React Navigation's `animationDuration` is an iOS-only option. On Android
 * react-native-screens ignores it outright — `ScreenViewManager.setTransitionDuration`
 * is literally `= Unit` — and hands the fragment transaction a fixed animation
 * resource per preset instead. So the preset picks the duration: `ios_from_right`
 * is `config_shortAnimTime` (200ms) and the next one down is `none` at 20ms,
 * which is a cut rather than a move. There is nothing in between to choose.
 *
 * Android resource merging gives us the missing step. Resources declared by the
 * app module outrank same-named ones from a library, so writing our own copy of
 * these four files quietly replaces the library's.
 *
 * We rewrite react-native-screens' own definitions rather than shipping copies
 * of them. Only the duration is ours; the offsets and interpolators stay
 * whatever the installed version says they are, so upgrading it changes the
 * animation and keeps our timing. If the files or the attribute ever move, the
 * asserts below stop the build — a silent return to 200ms would be a very
 * confusing thing to debug.
 *
 * This is native. Changing it needs a rebuild, not a reload.
 */

const DURATION_MS = 100;

/** The four halves of `ios_from_right`: a screen arriving and the one it covers, both ways. */
const ANIMATIONS = [
  'rns_ios_from_right_foreground_open',
  'rns_ios_from_right_background_open',
  'rns_ios_from_right_foreground_close',
  'rns_ios_from_right_background_close',
];

const DURATION_ATTRIBUTE = /android:duration="[^"]*"/g;

function sourceDirectory() {
  const packageJson = require.resolve('react-native-screens/package.json');
  return path.join(path.dirname(packageJson), 'android/src/main/res/base/anim');
}

function retime(xml, name) {
  const matches = xml.match(DURATION_ATTRIBUTE);

  if (matches?.length !== 1) {
    throw new Error(
      `with-stack-transition-duration: expected exactly one android:duration in ${name}.xml, ` +
        `found ${matches?.length ?? 0}. react-native-screens has changed shape; ` +
        `re-read its res/base/anim before trusting this plugin again.`,
    );
  }

  return xml.replace(DURATION_ATTRIBUTE, `android:duration="${DURATION_MS}"`);
}

module.exports = function withStackTransitionDuration(config) {
  return withDangerousMod(config, [
    'android',
    (modConfig) => {
      const from = sourceDirectory();
      const into = path.join(modConfig.modRequest.platformProjectRoot, 'app/src/main/res/anim');

      fs.mkdirSync(into, { recursive: true });

      for (const name of ANIMATIONS) {
        const source = path.join(from, `${name}.xml`);

        if (!fs.existsSync(source)) {
          throw new Error(
            `with-stack-transition-duration: ${name}.xml is gone from react-native-screens. ` +
              `The ios_from_right preset it belonged to may have been renamed or removed.`,
          );
        }

        const header =
          `<!--\n` +
          `  Generated by plugins/with-stack-transition-duration.js. Do not edit.\n` +
          `  Overrides react-native-screens' ${name} to run in ${DURATION_MS}ms.\n` +
          `-->\n`;

        const retimed = retime(fs.readFileSync(source, 'utf8'), name);

        fs.writeFileSync(
          path.join(into, `${name}.xml`),
          retimed.replace(/^(<\?xml[^>]*\?>\n)/, `$1${header}`),
          'utf8',
        );
      }

      return modConfig;
    },
  ]);
};
